import { chromium } from 'playwright';
import path from 'node:path';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const p = await (await b.newContext({ viewport: { width: 520, height: 860 }, deviceScaleFactor: 4 })).newPage();
await p.goto('file://' + path.resolve('single.html'));
await p.waitForLoadState('networkidle'); await p.waitForTimeout(300);
await p.screenshot({ path: 'mane-meals-phone-transparent.png', omitBackground: true });
await p.evaluate(() => document.body.classList.add('cream'));
await p.screenshot({ path: 'mane-meals-phone-cream.png' });
await b.close();
